/**
 * S1 spike, step 3: measure import inflation. For every source module (src/** and public/**, .mjs/.js/.cjs) start
 * a fresh node process that only imports it, under NODE_V8_COVERAGE, and keep the coverage.
 *
 *   node plans/spikes/s1/loadonly.mjs --assay <suite root> --out <dir> [--jobs 5]
 *   node plans/spikes/s1/reduce.mjs   --assay <suite root> --out <dir> --dir cov-load
 *
 * The stub first loads tests/support/cloudflare-modules.mjs (the suite's stand-ins for cloudflare:workers, so
 * Worker modules can link) and, for public/** modules, installs tests/support/dom.mjs (the suite's DOM double), as
 * the tests do; both live under tests/ and are not counted. It then does `await import(module)` and exits.
 * Every src/public line covered in any of these runs is a load-only line: covered by importing alone.
 * Writes <out>/cov-load/<slug>/coverage-*.json and <out>/loadonly.json (per module: ok or the import error).
 * Standard library only.
 */
import { spawn } from 'node:child_process';
import { mkdirSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const { values } = parseArgs({ options: { assay: { type: 'string' }, out: { type: 'string' }, jobs: { type: 'string', default: '5' } } });
if (!values.assay || !values.out) { console.error('usage: loadonly.mjs --assay <dir> --out <dir> [--jobs N]'); process.exit(2); }
const root = resolve(values.assay), out = resolve(values.out), jobs = Number(values.jobs);

function walk(dir, acc = []) {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
        if (e.name === 'node_modules') continue;
        const p = join(dir, e.name);
        if (e.isDirectory()) walk(p, acc); else if (/\.(mjs|cjs|js)$/.test(e.name)) acc.push(p);
    }
    return acc;
}
const modules = [...walk(resolve(root, 'src')), ...walk(resolve(root, 'public'))].map(p => p.slice(root.length + 1)).sort();

const stub = resolve(out, 'load-stub.mjs');
writeFileSync(stub, `// generated by plans/spikes/s1/loadonly.mjs
await import(${JSON.stringify(pathToFileURL(resolve(root, 'tests/support/cloudflare-modules.mjs')).href)});
const [rel] = process.argv.slice(2);
if (rel.startsWith('public/')) {
    try { (await import(${JSON.stringify(pathToFileURL(resolve(root, 'tests/support/dom.mjs')).href)})).installDom(); } catch (e) { console.log('DOM ' + e.message); }
}
try { await import(new URL(rel, ${JSON.stringify(pathToFileURL(root + '/').href)}).href); console.log('OK'); }
catch (e) { console.log('ERR ' + (e.code ?? e.name) + ': ' + String(e.message).split('\\n')[0].slice(0, 160)); }
process.exit(0);
`);
mkdirSync(resolve(out, 'cov-load'), { recursive: true });
const env = { ...process.env, PATH: `/opt/homebrew/bin:${process.env.PATH ?? ''}` };
const results = {}, queue = [...modules], t0 = performance.now();

function runOne(rel) {
    const dir = resolve(out, 'cov-load', rel.replaceAll('/', '__'));
    rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true });
    return new Promise(done => {
        const child = spawn(process.execPath, [stub, rel], { cwd: root, env: { ...env, NODE_V8_COVERAGE: dir }, stdio: ['ignore', 'pipe', 'pipe'] });
        let text = '';
        child.stdout.on('data', d => text += d); child.stderr.on('data', () => { });
        const timer = setTimeout(() => child.kill('SIGKILL'), 60_000);
        child.on('close', code => {
            clearTimeout(timer);
            const last = text.trim().split('\n').filter(l => /^(OK|ERR|DOM)/.test(l));
            results[rel] = { exit: code, status: last.at(-1) ?? 'NONE' };
            done();
        });
    });
}
await Promise.all(Array.from({ length: jobs }, async () => { while (queue.length) await runOne(queue.shift()); }));
const failed = Object.entries(results).filter(([, r]) => r.status !== 'OK');
const summary = { modules: modules.length, ok: modules.length - failed.length, failed: failed.length, jobs, wallMs: Math.round(performance.now() - t0), results };
writeFileSync(resolve(out, 'loadonly.json'), JSON.stringify(summary, null, 1));
console.log(JSON.stringify({ ...summary, results: undefined }));
for (const [m, r] of failed.slice(0, 30)) console.log(m, r.status);
